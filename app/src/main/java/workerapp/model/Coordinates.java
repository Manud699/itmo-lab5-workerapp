package workerapp.model;

public class Coordinates  {

    private float x;
    private Double y;

    
    public Coordinates(float x, Double y) {
        this.x = x; 
        this.y = y;
    } 

    public float getX() {
        return x; 
    } 
    

    public Double getY() {
        return y; 
    } 


}
